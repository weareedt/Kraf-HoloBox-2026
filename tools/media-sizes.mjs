/**
 * Record the exact byte size of every video, so a damaged copy is caught at startup.
 *
 * Why this exists. Johnny's `explain.mp4` once arrived in the project 164 KB LARGER than the
 * master and completely undecodable — 27,076 NAL errors, every frame broken, `profile` read
 * as `unknown` where the master says `High`. The startup check only asked whether the file
 * EXISTED, so it passed, the manifest loaded, the talk screen mounted, and the visitor got a
 * panel with a back button and no picture. Nothing anywhere said why.
 *
 * A size comparison would have named the file on the loading screen. It is not a checksum
 * and does not pretend to be: it cannot catch a same-length corruption, and hashing 4.3 GB
 * on every boot would be far too slow for a kiosk that is expected to be up in seconds. What
 * it does catch is the realistic failure — a copy that was interrupted, truncated, or
 * written by something that mangled it — which is what actually happened here.
 *
 * Run this whenever the video masters legitimately change, and commit the result. The sizes
 * are taken from the MIRROR by default, since that is the copy of record that co-workers
 * install from.
 *
 *   node tools/media-sizes.mjs                 # from ../HoloBox-media
 *   node tools/media-sizes.mjs --from=<dir>    # from somewhere else
 *   node tools/media-sizes.mjs --from=content  # from this project's own files
 */
import { readdirSync, statSync, writeFileSync, existsSync, lstatSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const arg = process.argv.find((a) => a.startsWith('--from='))?.slice(7);
const FROM = arg
  ? join(ROOT, arg)
  : join(ROOT, '..', 'HoloBox-media', 'content');
const OUT = join(ROOT, 'content', 'media-sizes.json');

if (!existsSync(FROM)) {
  console.error(`  ! no such folder: ${FROM}`);
  console.error('    Pass --from=<dir> pointing at the "content" folder to measure.');
  process.exit(1);
}

/* Recursive, NOT just `artists/<who>/video/`. Scanning only the video folders found 18
 * files where the mirror holds 32: Norhaiza's ten process-step clips and Samat's four live
 * under `artists/<who>/steps/`, and a damaged step video would have sailed through
 * unnoticed in exactly the way Johnny's talk did. */
const files = {};
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const abs = join(dir, name);
    const st = lstatSync(abs);
    if (st.isDirectory()) walk(abs);
    else if (st.isFile() && /\.(mp4|webm|mov)$/i.test(name)) {
      files[relative(FROM, abs).replace(/\\/g, '/')] = st.size;
    }
  }
}(join(FROM, 'artists')));

const total = Object.values(files).reduce((a, b) => a + b, 0);
writeFileSync(OUT, `${JSON.stringify({
  note: 'generated by tools/media-sizes.mjs — re-run and commit when the masters change',
  measuredFrom: relative(ROOT, FROM).replace(/\\/g, '/'),
  generated: new Date().toISOString().slice(0, 10),
  files,
}, null, 2)}\n`);

console.log(`  ${Object.keys(files).length} video files, ${(total / 2 ** 30).toFixed(2)} GB`);
console.log(`  > ${relative(ROOT, OUT).replace(/\\/g, '/')}`);
